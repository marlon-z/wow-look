const localeNames = {
  'zh-CN': '简体中文',
  'zh-TW': '繁體中文',
  'en-US': 'English US',
  'en-GB': 'English UK',
  'de-DE': 'Deutsch',
  'fr-FR': 'Français',
  'es-ES': 'Español EU',
  'es-MX': 'Español LATAM',
  'pt-BR': 'Português BR',
  'ko-KR': '한국어',
  'it-IT': 'Italiano',
  'ru-RU': 'Русский',
};

const localeOverrides = Object.fromEntries(
  Object.keys(localeNames).map((locale) => [
    locale,
    {
      data: DATA_BY_LOCALE[locale],
      ...UI_BY_LOCALE[locale],
    },
  ]),
);

export const SUPPORTED_LOCALES = Object.keys(localeNames);

export function getLocaleName(locale) {
  return localeNames[locale] || locale;
}

export function resolveLocale(requested) {
  if (requested && localeOverrides[requested]) return requested;
  const normalized = String(requested || '').replace('_', '-');
  if (localeOverrides[normalized]) return normalized;
  const lang = normalized.split('-')[0];
  if (lang === 'zh') return 'zh-CN';
  if (lang === 'en') return 'en-US';
  return SUPPORTED_LOCALES.find((locale) => locale.startsWith(`${lang}-`)) || 'zh-CN';
}

export function createI18n(locale) {
  const resolved = resolveLocale(locale);
  const dict = localeOverrides[resolved] || localeOverrides['zh-CN'];

  function get(path) {
    return path.split('.').reduce((value, key) => (value && value[key] !== undefined ? value[key] : undefined), dict);
  }

  function t(path, vars = {}) {
    const value = get(path);
    const fallback = path.split('.').reduce((acc, key) => (acc && acc[key] !== undefined ? acc[key] : undefined), localeOverrides['zh-CN']);
    const text = value !== undefined ? value : (fallback !== undefined ? fallback : path);
    return String(text).replace(/\{(\w+)\}/g, (_, key) => vars[key] !== undefined ? vars[key] : '');
  }

  return { locale: resolved, t, raw: get };
}
