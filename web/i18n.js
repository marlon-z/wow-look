function mapKeys(keys, values) {
  if (keys.length !== values.length) {
    throw new Error(`i18n section length mismatch: expected ${keys.length}, got ${values.length}`);
  }
  return Object.fromEntries(keys.map((key, index) => [key, values[index]]));
}

